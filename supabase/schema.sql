create policy "users update own avatar" on storage.objects for update to authenticated using (bucket_id='avatars' and (storage.foldername(name))[1] = auth.uid()::text) with check (bucket_id='avatars' and (storage.foldername(name))[1] = auth.uid()::text);

create or replace function public.admin_set_student_active(p_user_id uuid, p_is_active boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  update public.profiles set is_active = p_is_active, updated_at = now()
  where id = p_user_id and role = 'student';
  if not found then raise exception 'Data siswa tidak ditemukan'; end if;
end;
$$;
revoke all on function public.admin_set_student_active(uuid,boolean) from public;
grant execute on function public.admin_set_student_active(uuid,boolean) to authenticated;

