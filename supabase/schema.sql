-- ELORA Supabase / PostgreSQL schema
-- Jalankan seluruh file ini melalui Supabase Dashboard > SQL Editor.
-- Tabel users dan api_tokens MySQL digantikan oleh Supabase Auth + profiles.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.institutions (
  id bigint generated by default as identity primary key,
  name varchar(200) not null,
  type varchar(100) not null,
  location varchar(255) not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name varchar(100) not null,
  student_id varchar(50) unique,
  email text,
  role text not null default 'student' check (role in ('student','admin')),
  institution_id bigint references public.institutions(id) on delete set null,
  is_active boolean not null default true,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bills (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  institution_id bigint references public.institutions(id) on delete set null,
  bill_type varchar(100) not null default 'SPP',
  billing_month smallint not null check (billing_month between 1 and 12),
  billing_year smallint not null check (billing_year between 2020 and 2100),
  amount numeric(15,2) not null check (amount > 0),
  paid_amount numeric(15,2) not null default 0 check (paid_amount >= 0),
  due_date date not null,
  paid_at timestamp without time zone,
  status text not null default 'unpaid' check (status in ('unpaid','partial','paid')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_user_bill_period unique (user_id, bill_type, billing_month, billing_year),
  constraint chk_paid_amount check (paid_amount <= amount)
);

create table if not exists public.spp_config (
  id integer primary key default 1 check (id = 1),
  amount numeric(15,2) not null default 500000 check (amount > 0),
  due_day smallint not null default 10 check (due_day between 1 and 28),
  updated_at timestamptz not null default now()
);
insert into public.spp_config(id, amount, due_day) values (1, 500000, 10)
on conflict (id) do nothing;

create table if not exists public.payment_chain (
  id bigint generated by default as identity primary key,
  block_index bigint not null unique,
  bill_id bigint not null references public.bills(id) on delete restrict,
  user_id uuid not null references public.profiles(id) on delete restrict,
  student_id text not null,
  nama text not null,
  period varchar(7) not null,
  amount numeric(15,2) not null,
  old_status text not null,
  new_status text not null,
  changed_by_id uuid not null references public.profiles(id) on delete restrict,
  changed_by_name text not null,
  block_timestamp timestamp without time zone not null,
  previous_hash char(64) not null,
  block_hash char(64) not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title varchar(200) not null,
  body text not null,
  type varchar(50) not null default 'general',
  target text not null default 'all' check (target in ('all','user')),
  target_user_id uuid references public.profiles(id) on delete cascade,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint chk_notification_target check ((target = 'all' and target_user_id is null) or (target = 'user' and target_user_id is not null))
);

create table if not exists public.notification_reads (
  notification_id bigint not null references public.notifications(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key (notification_id, user_id)
);

create table if not exists public.fcm_tokens (
  token text primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  device_platform text,
  updated_at timestamptz not null default now()
);

create index if not exists idx_bills_user_period on public.bills(user_id, billing_year desc, billing_month desc);
create index if not exists idx_chain_user on public.payment_chain(user_id, block_index);
create index if not exists idx_notifications_target_created on public.notifications(target, created_at desc);
create index if not exists idx_fcm_user on public.fcm_tokens(user_id);

-- Profiles dibuat otomatis saat Supabase Auth sign-up.
-- Role selalu student; admin hanya dipromosikan dari SQL Editor oleh pemilik project.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_institution_id bigint;
  v_student_id text;
  v_full_name text;
begin
  v_student_id := nullif(trim(new.raw_user_meta_data ->> 'student_id'), '');
  v_full_name := coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), 'Pengguna ELORA');
  if new.raw_user_meta_data ? 'institution_id' then
    v_institution_id := (new.raw_user_meta_data ->> 'institution_id')::bigint;
    if not exists (select 1 from public.institutions where id = v_institution_id and is_active = true) then
      raise exception 'Institusi tidak ditemukan atau tidak aktif';
    end if;
  end if;
  insert into public.profiles(id, full_name, student_id, email, role, institution_id, is_active)
  values (new.id, v_full_name, v_student_id, new.email, 'student', v_institution_id, true);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and is_active = true
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- Atomic transaction: update bill + append its hash-chain block.
create or replace function public.admin_update_bill_status(p_bill_id bigint, p_new_status text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_bill public.bills%rowtype;
  v_student public.profiles%rowtype;
  v_admin public.profiles%rowtype;
  v_old_status text;
  v_paid numeric(15,2);
  v_paid_at timestamp without time zone;
  v_index bigint;
  v_previous_hash text;
  v_timestamp timestamp without time zone := date_trunc('second', now() at time zone 'UTC');
  v_period text;
  v_hash text;
begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  if p_new_status not in ('paid','unpaid') then raise exception 'Status pembayaran tidak valid'; end if;
  perform pg_advisory_xact_lock(73190421);
  select * into v_bill from public.bills where id = p_bill_id for update;
  if not found then raise exception 'Data tagihan tidak ditemukan'; end if;
  select * into v_student from public.profiles where id = v_bill.user_id;
  select * into v_admin from public.profiles where id = auth.uid();
  v_old_status := v_bill.status;
  v_paid := case when p_new_status = 'paid' then v_bill.amount else 0 end;
  v_paid_at := case when p_new_status = 'paid' then v_timestamp else null end;
  v_period := to_char(make_date(v_bill.billing_year::int, v_bill.billing_month::int, 1), 'YYYY-MM');

  update public.bills set status = p_new_status, paid_amount = v_paid, paid_at = v_paid_at, updated_at = now() where id = p_bill_id;
  select coalesce(max(block_index), 0) + 1 into v_index from public.payment_chain;
  select coalesce((select block_hash from public.payment_chain order by block_index desc limit 1), repeat('0',64)) into v_previous_hash;
  v_hash := encode(digest(
    v_index::text || p_bill_id::text || coalesce(v_student.student_id,'') || v_period ||
    v_old_status || p_new_status || auth.uid()::text ||
    to_char(v_timestamp, 'YYYY-MM-DD HH24:MI:SS') || v_previous_hash,
    'sha256'
  ), 'hex');

  insert into public.payment_chain(
    block_index,bill_id,user_id,student_id,nama,period,amount,old_status,new_status,
    changed_by_id,changed_by_name,block_timestamp,previous_hash,block_hash
  ) values (
    v_index,p_bill_id,v_bill.user_id,coalesce(v_student.student_id,''),v_student.full_name,v_period,
    v_bill.amount,v_old_status,p_new_status,auth.uid(),v_admin.full_name,v_timestamp,v_previous_hash,v_hash
  );
  return jsonb_build_object('success',true,'status',p_new_status,'block_index',v_index,'block_hash',v_hash);
end;
$$;
revoke all on function public.admin_update_bill_status(bigint,text) from public;
grant execute on function public.admin_update_bill_status(bigint,text) to authenticated;

create or replace function public.admin_generate_monthly_bills(p_month integer, p_year integer, p_amount numeric default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_config public.spp_config%rowtype;
  v_amount numeric(15,2);
  v_due_day integer;
  v_due_date date;
  v_inserted integer := 0;
  v_skipped integer := 0;
  v_count integer;
begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  if p_month < 1 or p_month > 12 then raise exception 'Bulan tidak valid (1-12)'; end if;
  if p_year < 2020 or p_year > 2100 then raise exception 'Tahun tidak valid'; end if;
  select * into v_config from public.spp_config where id = 1;
  v_amount := coalesce(p_amount, v_config.amount, 500000);
  if v_amount <= 0 then raise exception 'Nominal SPP harus lebih dari 0'; end if;
  v_due_day := least(coalesce(v_config.due_day,10), extract(day from (date_trunc('month', make_date(p_year,p_month,1)) + interval '1 month - 1 day'))::integer);
  v_due_date := make_date(p_year,p_month,v_due_day);
  select count(*) into v_count from public.profiles where role='student' and is_active=true;
  if v_count=0 then raise exception 'Tidak ada siswa aktif yang terdaftar'; end if;

  insert into public.bills(user_id,institution_id,bill_type,billing_month,billing_year,amount,paid_amount,due_date,status)
  select p.id,p.institution_id,'SPP',p_month,p_year,v_amount,0,v_due_date,'unpaid'
  from public.profiles p where p.role='student' and p.is_active=true
  on conflict (user_id,bill_type,billing_month,billing_year) do nothing;
  get diagnostics v_inserted = row_count;
  v_skipped := v_count - v_inserted;
  return jsonb_build_object(
    'success',true,
    'message',format('Tagihan SPP %s %s berhasil digenerate.',
      (array['','Januari','Februari','Maret','April','Mei','Juni','Juli','Agustus','September','Oktober','November','Desember'])[p_month],p_year),
    'inserted',v_inserted,'skipped',v_skipped,'period',to_char(make_date(p_year,p_month,1),'YYYY-MM'),'amount',v_amount,'due_date',v_due_date
  );
end;
$$;
revoke all on function public.admin_generate_monthly_bills(integer,integer,numeric) from public;
grant execute on function public.admin_generate_monthly_bills(integer,integer,numeric) to authenticated;

