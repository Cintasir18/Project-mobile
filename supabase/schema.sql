drop policy if exists "admins insert bills" on public.bills;
create policy "admins insert bills" on public.bills for insert to authenticated with check (public.is_admin());

drop policy if exists "admins manage spp config" on public.spp_config;
create policy "admins manage spp config" on public.spp_config for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "users read own chain and admins read all" on public.payment_chain;
