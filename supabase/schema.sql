drop policy if exists "active institutions are readable" on public.institutions;
create policy "active institutions are readable" on public.institutions for select to anon, authenticated using (is_active = true or public.is_admin());
drop policy if exists "admins manage institutions" on public.institutions;
create policy "admins manage institutions" on public.institutions for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "users read own profile or admins read all" on public.profiles;
create policy "users read own profile or admins read all" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
revoke update on public.profiles from anon, authenticated;
grant update (avatar_url) on public.profiles to authenticated;
drop policy if exists "users update own avatar" on public.profiles;
create policy "users update own avatar" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
drop policy if exists "admins update profiles" on public.profiles;
-- Status updates intentionally go through privileged RPCs; no broad admin table update grant.

drop policy if exists "students read own bills and admins read all" on public.bills;
