drop policy if exists "users read their notifications" on public.notifications;
create policy "users read their notifications" on public.notifications for select to authenticated using (target = 'all' or target_user_id = auth.uid() or public.is_admin());
drop policy if exists "users manage own notification reads" on public.notification_reads;
create policy "users manage own notification reads" on public.notification_reads for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "users manage own fcm tokens" on public.fcm_tokens;
create policy "users manage own fcm tokens" on public.fcm_tokens for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

